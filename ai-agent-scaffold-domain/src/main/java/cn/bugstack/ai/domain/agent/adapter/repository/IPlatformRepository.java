package cn.bugstack.ai.domain.agent.adapter.repository;

/**
 * 平台数据库的连通性探针。
 *
 * <p>解决什么问题：数据库地基先搭好，但具体的会话、用量、RAG、调度等读写用例还没拆出来。
 * 这个接口先给出一个最小能力——确认库连得上，让健康检查和启动自检有东西可调。</p>
 *
 * <p>所属层次：领域层的仓储接口（出口），实现在基础设施层。</p>
 *
 * <p>它不负责什么：不承载任何业务读写；真正的业务用例会按会话、用量、RAG 等领域另开仓储接口，
 * 不要把新方法堆到这里。</p>
 */
public interface IPlatformRepository {

    /**
     * 探测平台数据库是否可用。
     *
     * <p>返回 true 表示连接和最基本的查询都正常；返回 false 表示库不可用，
     * 上层应据此判断当前只能提供不依赖持久化的能力，而不是继续往下跑然后中途失败。</p>
     */
    boolean available();
}
