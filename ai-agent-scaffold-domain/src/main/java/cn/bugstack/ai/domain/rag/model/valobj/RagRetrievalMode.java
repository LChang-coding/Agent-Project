package cn.bugstack.ai.domain.rag.model.valobj;

/**
 * 一次检索要开哪几条召回通道。
 *
 * <p>属于哪一层：领域层值对象，是检索配置（RagRetrievalProfileEntity）的核心开关。</p>
 *
 * <p>谁会读它：检索配置在构造时用它校验「该模式必需的候选数不能为 0」；
 * 检索服务用它决定要不要调用 Embedding 模型、要不要调用稀疏编码器、要不要做融合。
 * 选错模式的直接后果是白花一次模型调用，或者该召回的资料一条都召不回来。</p>
 *
 * <p>它不负责什么：不决定融合怎么做（那是 RagFusionStrategy），也不决定取多少条（那是各个 topK）。</p>
 */
public enum RagRetrievalMode {

    /**
     * 只走语义向量召回：把问题送进 Embedding 模型换成一条稠密向量，再去向量库找语义最接近的分块。
     *
     * <p>选择它时 denseTopK 必须大于 0，否则配置校验直接拒绝。</p>
     *
   * <p>擅长「换了说法也能找到」，但对精确的编号、型号、专有名词容易漏召。</p>
     */
    DENSE,

    /**
     * 只走词项稀疏召回：把问题拆成带权重的词项，靠字面命中找分块。
     *
 * <p>选择它时 sparseTopK 必须大于 0。</p>
     *
     * <p>擅长精确匹配关键词和编号，但换个说法就找不到。</p>
     */
    SPARSE,

    /**
     * 两条通道同时召回，再把两份候选融合成一份排名。
     *
     * <p>选择它时 denseTopK 和 sparseTopK 都必须大于 0，而且融合策略不能是 NONE、
     * 两个融合权重不能同时为 0，否则配置校验会拒绝——因为那样融合出来一定是空的。</p>
     *
     * <p>代价是一次检索要调两个模型，耗时和费用都更高。</p>
     */
    HYBRID
}
