package cn.bugstack.ai.domain.run.model;

/**
 * 工具执行闸门的放行结论：这次工具调用到底能不能真的发出去。
 *
 * <p>解决什么问题：模型说「我要调这个工具、参数是这些」，但从模型说完到工具真正执行之间有一段时间差。
 * 这段时间里用户可能点了取消，历史也可能被压缩过。压缩会改变提示词事实，模型基于旧历史算出的参数就不再可信。
 * 所以在真正产生外部副作用之前，必须由闸门给出一个明确结论。</p>
 *
 * <p>所属层次：领域层运行模型。由 {@code RunExecutionGate#beforeTool} 返回，
 * 由工具调用链路（Agent 工具回调、工作流工具节点）按结论决定继续还是重来。</p>
 *
 * <p>它不负责什么：不做取消判断本身（那在 RunControlService 里查数据库），也不执行工具，只表达结论。
 * 注意「已取消」不在这个枚举里：取消是直接抛业务异常中断整条链路，不走放行结论这条路。</p>
 */
public enum ToolGateDecision {
    /** 运行状态仍可执行、上下文版本也没变，允许真的调用外部工具并产生副作用。 */
    ALLOW,
    /** 工具执行前刚发生过历史压缩，模型旧的工具参数已基于失效历史，必须丢弃并用新上下文重新推理一轮。 */
    RETRY_MODEL
}
