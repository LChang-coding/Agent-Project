    KEY idx_wo_aggregate (tenant_id, aggregate_type, aggregate_id, id),
    KEY idx_wo_trace (trace_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='智能工作流事务消息箱';
